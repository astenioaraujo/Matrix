-- Reclassificação de lançamentos (Fluxo de Caixa, importação analítica)
--
-- A classificação automática trabalha pela CONTA do WebPostos: toda a
-- "2.03.03.003 - COMPRA MATERIAL TECNOLOGIA/ASSISTENCIA INFORMATICA" vai
-- para uma conta gerencial só. Algumas linhas de dentro dela, porém, são de
-- outra natureza — a Tecnofort (segurança eletrônica) é investimento, não
-- despesa de informática.
--
-- Cada regra procura um texto na descrição do lançamento detalhado (e,
-- opcionalmente, só dentro de uma conta do WebPostos). Após a importação,
-- para cada lançamento que casa:
--   1. a conta de origem recebe o ESTORNO (sinal invertido), que zera o
--      valor dela sem apagar o lançamento original do detalhamento;
--   2. nasce um lançamento "RECLASSIFICADO - <destino>" com o valor original,
--      que a classificação automática (de-para) leva para a conta gerencial.
-- Os dois lados têm detalhamento, então a conferência continua fechando.

CREATE TABLE IF NOT EXISTS public.reclassificacoes_lancamentos (
    id_reclassificacao integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa        character varying NOT NULL,
    texto              character varying NOT NULL,   -- contido na descrição do lançamento
    codigo_conta       character varying,            -- conta do WebPostos (ex.: 2.03.03.003); vazio = qualquer conta
    destino            character varying NOT NULL,   -- nome do lançamento novo (ex.: INVESTIMENTOS)
    ativo              boolean NOT NULL DEFAULT true,
    ordem              integer DEFAULT 10,
    criado_em          timestamp without time zone DEFAULT now(),
    atualizado_em      timestamp without time zone DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_reclassificacoes_lancamentos_empresa
    ON public.reclassificacoes_lancamentos (cod_empresa);

ALTER TABLE public.reclassificacoes_lancamentos ENABLE ROW LEVEL SECURITY;

-- Carga EMP012 (30 Set CZ): Tecnofort na compra de material de tecnologia
-- vai para Investimentos. No WebPostos o nome vem "TECNOFORT COM. E SERVICOS
-- DE MAT. DE SEG. ELETRONICA" (sem o E final).
INSERT INTO public.reclassificacoes_lancamentos (cod_empresa, texto, codigo_conta, destino)
SELECT 'EMP012', 'TECNOFORT', '2.03.03.003', 'INVESTIMENTOS'
WHERE NOT EXISTS (
    SELECT 1 FROM public.reclassificacoes_lancamentos
    WHERE cod_empresa = 'EMP012' AND texto = 'TECNOFORT'
);

-- De-para do lançamento novo: Investimentos = 5/1.
INSERT INTO public.classificacoes_automaticas (cod_empresa, texto, cod_grupo, cod_conta)
SELECT 'EMP012', 'RECLASSIFICADO - INVESTIMENTOS', 5, 1
WHERE NOT EXISTS (
    SELECT 1 FROM public.classificacoes_automaticas
    WHERE cod_empresa = 'EMP012' AND texto = 'RECLASSIFICADO - INVESTIMENTOS'
);

-- A conta 5/1 ("Moveis e Utensílios") passa a se chamar Investimentos.
-- Só a descrição: as colunas-chave são protegidas por trigger.
UPDATE public.contas_gerenciais
   SET descricao = 'Investimentos'
 WHERE cod_empresa = 'EMP012' AND cod_grupo = 5 AND cod_conta = 1;
