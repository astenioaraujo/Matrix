-- Parâmetros do ciclo de drenagem de tanques, uma linha por empresa (10/11/2026).
--
-- Mesmo desenho de afericoes_parametros: dia_semana (0 = segunda ... 4 = sexta),
-- frequencia (SEMANAL, DUAS_SEMANAS, TRES_SEMANAS, MENSAL) e data_referencia (só
-- em 2 ou 3 semanas). Empresa sem linha = sem aviso de drenagem faltante.
-- O aviso só cobra a partir da primeira drenagem lançada na empresa.

CREATE TABLE IF NOT EXISTS public.drenagens_parametros (
    id_parametro     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa      character varying NOT NULL UNIQUE,
    dia_semana       integer NOT NULL,
    frequencia       character varying NOT NULL DEFAULT 'SEMANAL',
    data_referencia  date,
    criado_em        timestamp without time zone DEFAULT now(),
    atualizado_em    timestamp without time zone DEFAULT now()
);

ALTER TABLE public.drenagens_parametros ENABLE ROW LEVEL SECURITY;

