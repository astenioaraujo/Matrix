-- Drenagem de Tanques de diesel (Operações → Drenagem de Tanques), 10/11/2026
--
-- Transcreve o formulário em papel "Dados da drenagem do fundo de tanques de
-- óleo diesel" (Resolução ANP 968/2024, art. 21) da Rede Lucena: uma folha =
-- um posto, uma data, um responsável e até 5 colunas de tanque.
--
--   drenagens           → a folha (filial, data, hora, responsável)
--   drenagens_tanques   → cada coluna da folha (até 5, só S10 e S500)
--   drenagens_arquivos  → fotos/vídeos do volume drenado
--
-- RG e assinatura do responsável NÃO são guardados (decisão do cliente: não
-- manter documento pessoal no sistema) — só o nome.
--
-- Retenção: a drenagem fica para sempre; as fotos/vídeos com mais de 6 meses
-- são apagados pela aplicação a cada novo envio (mesmo princípio das aferições).

BEGIN;

CREATE TABLE IF NOT EXISTS public.drenagens (
    id_drenagem     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa     character varying NOT NULL,
    cod_filial      integer NOT NULL,
    data_drenagem   date NOT NULL,
    hora_drenagem   time without time zone NOT NULL,
    responsavel     character varying NOT NULL,
    id_usuario      integer NOT NULL,
    criado_em       timestamp without time zone DEFAULT now(),
    atualizado_em   timestamp without time zone DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_drenagens_filial_data
    ON public.drenagens (cod_empresa, cod_filial, data_drenagem);

ALTER TABLE public.drenagens ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS public.drenagens_tanques (
    id_drenagem_tanque      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_drenagem             integer NOT NULL REFERENCES public.drenagens(id_drenagem) ON DELETE CASCADE,
    cod_empresa             character varying NOT NULL,
    tanque                  character varying NOT NULL,   -- como está pintado no posto: "TQ 3"
    cod_produto             character varying NOT NULL,   -- só diesel (S10 / S500)
    capacidade_litros       numeric,
    agua_medidor_mm         numeric NOT NULL DEFAULT 0,
    aspecto                 character varying,            -- "LII" = límpido e isento de impurezas
    cor                     character varying,
    volume_amostra_litros   numeric,
    presenca_agua           boolean NOT NULL DEFAULT false,
    volume_agua_litros      numeric NOT NULL DEFAULT 0,
    ordem                   integer DEFAULT 10,
    criado_em               timestamp without time zone DEFAULT now(),
    atualizado_em           timestamp without time zone DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_drenagens_tanques_drenagem
    ON public.drenagens_tanques (id_drenagem);

ALTER TABLE public.drenagens_tanques ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS public.drenagens_arquivos (
    id_arquivo          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_drenagem         integer NOT NULL REFERENCES public.drenagens(id_drenagem) ON DELETE CASCADE,
    cod_empresa         character varying NOT NULL,
    tipo                character varying NOT NULL,   -- 'video' ou 'imagem'
    arquivo             character varying NOT NULL,   -- caminho no bucket "drenagens"
    tamanho_bytes       bigint,
    duracao_segundos    numeric,
    capturado_em        timestamp without time zone,  -- quando a foto foi tirada (EXIF ou relógio do aparelho)
    criado_em           timestamp without time zone DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_drenagens_arquivos_drenagem
    ON public.drenagens_arquivos (id_drenagem);

ALTER TABLE public.drenagens_arquivos ENABLE ROW LEVEL SECURITY;

INSERT INTO public.permissoes_catalogo (sistema, opcao, descricao, ordem, ativo)
SELECT v.sistema, v.opcao, v.descricao, v.ordem, true
  FROM (VALUES
      ('OPERACOES', 'MENU_DRENAGENS',      'Menu de Drenagem de Tanques', 515),
      ('OPERACOES', 'INFORMAR_DRENAGENS',  'Informar Drenagens',          520),
      ('OPERACOES', 'CONSULTAR_DRENAGENS', 'Consultar Drenagens',         525)
  ) AS v(sistema, opcao, descricao, ordem)
 WHERE NOT EXISTS (
     SELECT 1 FROM public.permissoes_catalogo p
      WHERE p.sistema = v.sistema AND p.opcao = v.opcao
 );

COMMIT;
