-- Aferições de Bicos — vários arquivos por aferição (26/10/2026)
--
-- Pedido do cliente: às vezes o registro da aferição é uma foto do balde com
-- a régua/marcação, não um vídeo — e às vezes os dois juntos (vídeo da
-- descarga + foto do resultado). Uma aferição deixa de ter um arquivo só.
--
-- `afericoes.arquivo_video` não existe mais; os arquivos (vídeo e/ou imagem,
-- 1 ou mais) viram linhas em afericoes_arquivos. ON DELETE CASCADE: apagar a
-- aferição (retenção das 2 últimas por bico) já leva os arquivos do banco
-- junto — só o Storage continua tendo que ser limpo à parte pela aplicação.

CREATE TABLE IF NOT EXISTS public.afericoes_arquivos (
    id_arquivo   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_afericao  integer NOT NULL REFERENCES public.afericoes(id_afericao) ON DELETE CASCADE,
    tipo         character varying NOT NULL, -- 'video' ou 'imagem'
    arquivo      character varying NOT NULL, -- caminho no bucket "afericoes" do Storage
    criado_em    timestamp without time zone DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_afericoes_arquivos_afericao
    ON public.afericoes_arquivos (id_afericao);

ALTER TABLE public.afericoes_arquivos ENABLE ROW LEVEL SECURITY;

-- Tabela nova, sem aferição real cadastrada ainda: a coluna some, não precisa
-- de passo de migração de dados.
ALTER TABLE public.afericoes DROP COLUMN IF EXISTS arquivo_video;
