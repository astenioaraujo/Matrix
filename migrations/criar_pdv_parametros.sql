SELECT 'CONFIGURACOES', 'CONFIGURACAO_PDV', 'Configuração de PDV', 1720, TRUE
WHERE NOT EXISTS (
    SELECT 1 FROM permissoes_catalogo
    WHERE sistema = 'CONFIGURACOES' AND opcao = 'CONFIGURACAO_PDV'
);

