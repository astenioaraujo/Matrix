-- Histórico das importações do Fluxo de Caixa (Financeiro → Fluxo de Caixa →
-- Importações). Cada rota de importação (PDF sintético, PDF analítico, CSV O
-- Closet) grava uma linha aqui ao concluir com sucesso, para alimentar o
-- botão "Histórico" com as últimas 20 importações: data/hora, usuário e
-- total de registros importados.

CREATE TABLE IF NOT EXISTS public.importacoes_historico (
    id_historico     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa      character varying NOT NULL,
    id_usuario       integer,
    nome_usuario     character varying,
    tipo_importacao  character varying NOT NULL,
    total_registros  integer NOT NULL DEFAULT 0,
    criado_em        timestamp without time zone DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_importacoes_historico_empresa_data
    ON public.importacoes_historico (cod_empresa, criado_em DESC);

ALTER TABLE public.importacoes_historico ENABLE ROW LEVEL SECURITY;
