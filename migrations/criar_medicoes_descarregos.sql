-- Descarrego lançado em Informar Medições vira controle próprio, separado
-- do estoque (27/11/2026).
--
-- O descarrego lançado pelo lápis em Informar Medições
-- (adicionar_motorista_descarregos_medicoes.sql, 26/11/2026) gravava em
-- descarregos_combustiveis — a mesma tabela que Informar Descarregos usa
-- para fechar a compra e alimentar estoque/demais módulos. Isso estava
-- errado: são duas quantidades distintas. A que o departamento de
-- Operações digita em Informar Descarregos é a que manda no estoque e não
-- pode ser tocada por este lançamento. A que o gerente digita em Informar
-- Medições é outro controle (a diferença mostrada ali e em Perdas e Sobras
-- por Motorista) e não deve fechar compra nem mexer em saldo de estoque.
--
-- Esta tabela nova é exclusiva desse controle. data_medicao é a medição
-- que o gerente estava preenchendo; data_descarrego é sempre a véspera
-- (mesma regra de sempre — ver _data_descarrego_da_medicao).

BEGIN;

CREATE TABLE IF NOT EXISTS public.medicoes_descarregos (
    id_medicao_descarrego  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa            character varying NOT NULL,
    cod_filial             integer NOT NULL,
    cod_produto            character varying NOT NULL,
    data_medicao           date NOT NULL,
    data_descarrego        date NOT NULL,
    id_compra              integer REFERENCES public.compras_combustiveis(id_compra),
    quantidade_descarregada numeric NOT NULL,
    id_motorista           integer REFERENCES public.logistica_motoristas(id_motorista),
    hora_descarrego        time without time zone,
    criado_em              timestamp without time zone DEFAULT now(),
    atualizado_em          timestamp without time zone DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_medicoes_descarregos_filtro
    ON public.medicoes_descarregos (cod_empresa, cod_filial, cod_produto, data_medicao);

ALTER TABLE public.medicoes_descarregos ENABLE ROW LEVEL SECURITY;

COMMIT;
