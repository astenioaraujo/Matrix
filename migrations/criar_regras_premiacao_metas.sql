-- Regras de premiação por meta de vendas (Performance de Gerentes → Regras de
-- Premiação). Uma regra vale do mês de vigência até a próxima: mudar a regra é
-- cadastrar outra vigência, e os meses anteriores continuam com a antiga — senão
-- o prêmio de um mês já pago mudaria sozinho.
--
-- O prêmio nunca é gravado: é calculado na consulta do Acompanhamento de Metas.
-- A tabela "Meta + N litros" do PDF também não: sai destes três números.

CREATE TABLE IF NOT EXISTS vendas_premiacao_regras (
    id_vendas_premiacao_regra integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa character varying NOT NULL,
    vigencia_ano integer NOT NULL,
    vigencia_mes integer NOT NULL CHECK (vigencia_mes BETWEEN 1 AND 12),
    premio_meta numeric(14, 2) NOT NULL CHECK (premio_meta >= 0),
    litros_faixa integer NOT NULL CHECK (litros_faixa > 0),
    premio_faixa numeric(14, 2) NOT NULL CHECK (premio_faixa >= 0),
    criado_em timestamp without time zone DEFAULT now(),
    atualizado_em timestamp without time zone DEFAULT now(),
    UNIQUE (cod_empresa, vigencia_ano, vigencia_mes)
);

ALTER TABLE public.vendas_premiacao_regras ENABLE ROW LEVEL SECURITY;

-- Não é concedida a ninguém: só o superusuário passa por bypass.
INSERT INTO permissoes_catalogo (sistema, opcao, descricao, ordem, ativo)
SELECT v.sistema, v.opcao, v.descricao, v.ordem, TRUE
FROM (VALUES
    ('PERFORMANCES', 'REGRAS_PREMIACAO', 'Performance de Gerentes - Regras de Premiação', 1197)
) AS v(sistema, opcao, descricao, ordem)
WHERE NOT EXISTS (
    SELECT 1 FROM permissoes_catalogo p
    WHERE p.sistema = v.sistema AND p.opcao = v.opcao
);

