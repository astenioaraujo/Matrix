-- Cadastro de Bombas e Bicos (Operações → Configurações de Operações), 24/11/2026
--
-- Cada linha é um bico de uma bomba, vinculado ao combustível que ele abastece.
-- Sem versionamento por data por enquanto (decisão do cliente, 24/11/2026):
-- só a configuração atual importa, cadastro é upsert por
-- (cod_empresa, cod_filial, numero_bomba, numero_bico).
--
-- Sem FK para `combustiveis`/`filiais` — mesmo padrão de `capacidade_tanques`
-- (chave composta `cod_empresa, cod_filial`, sem referenciar `filiais.id`).

BEGIN;

CREATE TABLE IF NOT EXISTS public.bombas_bicos (
    id_bomba_bico   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa     character varying NOT NULL,
    cod_filial      integer NOT NULL,
    numero_bomba    integer NOT NULL,
    numero_bico     integer NOT NULL,
    cod_produto     character varying NOT NULL,
    criado_em       timestamp without time zone DEFAULT now(),
    atualizado_em   timestamp without time zone DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_bombas_bicos
    ON public.bombas_bicos (cod_empresa, cod_filial, numero_bomba, numero_bico);

ALTER TABLE public.bombas_bicos ENABLE ROW LEVEL SECURITY;

INSERT INTO public.permissoes_catalogo (sistema, opcao, descricao, ordem, ativo)
SELECT v.sistema, v.opcao, v.descricao, v.ordem, true
  FROM (VALUES
      ('OPERACOES', 'BOMBAS_BICOS', 'Bombas e Bicos', 530)
  ) AS v(sistema, opcao, descricao, ordem)
 WHERE NOT EXISTS (
     SELECT 1 FROM public.permissoes_catalogo p
      WHERE p.sistema = v.sistema AND p.opcao = v.opcao
 );

COMMIT;
