-- Avaliações de Funcionários: "Criar Avaliações".
--
-- Antes a avaliação nascia dentro de Executar, funcionário a funcionário (ou em
-- bloco por cargo), e não havia nada que dissesse "a filial X tem avaliação em
-- outubro com o checklist Y". Agora a avaliação é criada por filial e mês
-- (performances_avaliacoes_filiais) e os funcionários são VINCULADOS a ela —
-- o vínculo é a própria execução (performances_execucoes), uma por
-- funcionário, que é o que o chefe de pista preenche. Não há tabela de vínculo
-- à parte: seria a mesma verdade em dois lugares.

CREATE TABLE IF NOT EXISTS public.performances_avaliacoes_filiais (
    id_avaliacao_filial integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa         character varying NOT NULL,
    cod_filial          integer NOT NULL,
    ano                 integer NOT NULL,
    mes                 integer NOT NULL CHECK (mes BETWEEN 1 AND 12),
    id_avaliacao        bigint NOT NULL REFERENCES public.performances_avaliacoes (id_avaliacao),
    id_cargo            integer,          -- cargo usado na criação (informativo)
    criado_por          integer,
    criado_em           timestamp without time zone NOT NULL DEFAULT now(),
    atualizado_em       timestamp without time zone NOT NULL DEFAULT now(),
    UNIQUE (cod_empresa, cod_filial, ano, mes, id_avaliacao)
);

ALTER TABLE public.performances_avaliacoes_filiais ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.performances_execucoes
    ADD COLUMN IF NOT EXISTS id_avaliacao_filial integer
        REFERENCES public.performances_avaliacoes_filiais (id_avaliacao_filial);

CREATE INDEX IF NOT EXISTS ix_performances_execucoes_avaliacao_filial
    ON public.performances_execucoes (id_avaliacao_filial);

-- As execuções que já existiam ganham o cabeçalho correspondente
-- (empresa, filial, mês, checklist), para aparecerem em Criar Avaliações.
INSERT INTO public.performances_avaliacoes_filiais
    (cod_empresa, cod_filial, ano, mes, id_avaliacao)
SELECT DISTINCT
    e.cod_empresa,
    e.cod_filial,
    EXTRACT(YEAR FROM e.data_avaliacao)::int,
    EXTRACT(MONTH FROM e.data_avaliacao)::int,
    e.id_avaliacao
FROM public.performances_execucoes e
WHERE e.id_avaliacao_filial IS NULL
ON CONFLICT DO NOTHING;

UPDATE public.performances_execucoes e
SET id_avaliacao_filial = af.id_avaliacao_filial
FROM public.performances_avaliacoes_filiais af
WHERE e.id_avaliacao_filial IS NULL
  AND af.cod_empresa  = e.cod_empresa
  AND af.cod_filial   = e.cod_filial
  AND af.ano          = EXTRACT(YEAR FROM e.data_avaliacao)::int
  AND af.mes          = EXTRACT(MONTH FROM e.data_avaliacao)::int
  AND af.id_avaliacao = e.id_avaliacao;

-- Não concedida a ninguém: só o superusuário passa por bypass.
