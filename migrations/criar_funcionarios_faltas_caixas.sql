-- Funcionários de Faltas de Caixa — cadastro e transferência de filial
-- (26/11/2026), ligados pelo NOME, não pela matrícula da planilha: testado
-- com os dados reais da EMP012, a matrícula se repete entre postos (cada
-- posto numera do zero — WebPostos trata cada posto como um cadastro
-- separado), então não identifica ninguém na empresa toda. O nome
-- funciona melhor (só 2 de 73 colidem, ambos nomes incompletos — "CARLOS",
-- "PAULO" — a serem corrigidos na origem).
--
-- Tabela própria, não é o `funcionarios`/`funcionarios_movimentacoes` do
-- RH: lá a identidade é a matrícula (única por empresa,
-- `funcionarios_empresa_matricula_unica`), aqui é o nome — são conceitos
-- diferentes, misturar teria juntado gente errada.

CREATE TABLE public.caixas_faltas_sobras_funcionarios (
    id                 integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    cod_empresa        character varying NOT NULL,
    nome_funcionario   character varying NOT NULL,
    cod_filial         integer NOT NULL,
    ativo              boolean NOT NULL DEFAULT true,
    criado_em          timestamp without time zone NOT NULL DEFAULT now(),
    atualizado_em      timestamp without time zone NOT NULL DEFAULT now(),
    UNIQUE (cod_empresa, nome_funcionario)
);

CREATE TABLE public.caixas_faltas_sobras_funcionarios_movimentacoes (
    id                   integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    cod_empresa          character varying NOT NULL,
    id_funcionario       integer NOT NULL REFERENCES public.caixas_faltas_sobras_funcionarios (id),
    data_movimento       date NOT NULL,
    cod_filial_origem    integer,
    cod_filial_destino   integer NOT NULL,
    observacao           character varying,
    criado_em            timestamp without time zone NOT NULL DEFAULT now()
);

CREATE INDEX idx_caixas_faltas_sobras_funcionarios_movimentacoes_funcionario
    ON public.caixas_faltas_sobras_funcionarios_movimentacoes (id_funcionario, data_movimento);

ALTER TABLE public.caixas_faltas_sobras_funcionarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.caixas_faltas_sobras_funcionarios_movimentacoes ENABLE ROW LEVEL SECURITY;
