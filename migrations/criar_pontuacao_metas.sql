-- Pontuação por meta de vendas: quem bate a meta do mês pontua pela colocação
-- (o % atingido na rede), e os pontos acumulam dentro de um período.
--
-- O período é da empresa e carrega a própria tabela de pontos: mudar a regra no
-- período seguinte não altera os pontos já ganhos. Os pontos nunca são gravados
-- (nem os do mês, nem o acumulado): saem das vendas e das metas na consulta.
-- Sobreposição de períodos é recusada na gravação.

CREATE TABLE IF NOT EXISTS vendas_pontuacao_periodos (
    id_vendas_pontuacao_periodo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa character varying NOT NULL,
    ano_inicio integer NOT NULL,
    mes_inicio integer NOT NULL CHECK (mes_inicio BETWEEN 1 AND 12),
    ano_fim integer NOT NULL,
    mes_fim integer NOT NULL CHECK (mes_fim BETWEEN 1 AND 12),
    pontos_1 integer NOT NULL DEFAULT 10 CHECK (pontos_1 >= 0),
    pontos_2 integer NOT NULL DEFAULT 8 CHECK (pontos_2 >= 0),
    pontos_3 integer NOT NULL DEFAULT 6 CHECK (pontos_3 >= 0),
    pontos_4 integer NOT NULL DEFAULT 4 CHECK (pontos_4 >= 0),
    pontos_demais integer NOT NULL DEFAULT 2 CHECK (pontos_demais >= 0),
    criado_em timestamp without time zone DEFAULT now(),
    atualizado_em timestamp without time zone DEFAULT now(),
    CHECK ((ano_fim, mes_fim) >= (ano_inicio, mes_inicio)),
    UNIQUE (cod_empresa, ano_inicio, mes_inicio)
);

ALTER TABLE public.vendas_pontuacao_periodos ENABLE ROW LEVEL SECURITY;

