-- =====================================================================
-- Faltas e Sobras de Caixa — importação da planilha "Sobras e Faltas de
-- Caixa" (gerada pelo WebPostos: uma aba, um bloco por filial, dentro
-- dele um bloco por funcionário com as linhas Data/Turno/PDV/Sobra/Falta/
-- Diferença/Acumulado e um "Subtotal:" no fim de cada funcionário).
--
-- Guarda sobra e falta por lançamento (data + turno + pdv + funcionário);
-- a diferença do dia por funcionário e o TOTAL DO DIA são calculados na
-- consulta (convenção do projeto: nada de total/diferença persistido).
--
-- Reimportação: a tela apaga o período (cod_empresa, cod_filial, data
-- entre o menor e o maior dia vindos da planilha para aquela filial) e
-- insere de novo — mesmo desenho das outras importações do WebPostos.
-- =====================================================================

CREATE TABLE public.caixas_faltas_sobras (
    id_falta_sobra        integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    cod_empresa           character varying NOT NULL,
    cod_filial             integer NOT NULL,
    data                  date NOT NULL,
    turno                 integer,
    pdv                   character varying,
    matricula_funcionario character varying,
    nome_funcionario      character varying NOT NULL,
    sobra                 numeric(14,2) NOT NULL DEFAULT 0,
    falta                 numeric(14,2) NOT NULL DEFAULT 0,
    criado_em             timestamp without time zone NOT NULL DEFAULT now(),
    id_usuario_importou   integer REFERENCES public.usuarios (id_usuario)
);

CREATE INDEX idx_caixas_faltas_sobras_periodo
    ON public.caixas_faltas_sobras (cod_empresa, cod_filial, data);

ALTER TABLE public.caixas_faltas_sobras ENABLE ROW LEVEL SECURITY;

INSERT INTO permissoes_catalogo (sistema, opcao, descricao, ordem, ativo)
SELECT 'FINANCEIRO', 'FALTAS_CAIXAS', 'Faltas e Sobras de Caixa', 504, true
WHERE NOT EXISTS (
    SELECT 1 FROM permissoes_catalogo WHERE sistema = 'FINANCEIRO' AND opcao = 'FALTAS_CAIXAS'
);
