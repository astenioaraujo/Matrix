-- Finanças Pessoais: orçamento passa a ser MENSAL (11/11/2026).
--
-- Antes era um valor só por classificação (fp_classificacoes.valor_orcado),
-- que valia igual para todos os meses: mudar o valor reescrevia o orçado do
-- passado, e não havia como uma conta sair do orçamento a partir de um mês.
--
-- Agora: uma linha por classificação × competência (dia 1 do mês). Mês sem
-- linha = sem orçamento (orçado zero). O valor guarda o sinal que o usuário
-- digita (despesa negativa, receita positiva), como antes.
--
-- fp_classificacoes.valor_orcado deixa de ser lido pela aplicação; fica na
-- tabela só como registro do valor antigo. ajustar_ao_real continua na
-- classificação (é comportamento, não valor do mês).

CREATE TABLE IF NOT EXISTS public.fp_orcamentos_mensais (
    id_orcamento_mensal integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario          integer NOT NULL,
    id_classificacao    integer NOT NULL REFERENCES public.fp_classificacoes(id) ON DELETE CASCADE,
    competencia         date    NOT NULL,
    valor_orcado        numeric(14,2) NOT NULL,
    criado_em           timestamp without time zone DEFAULT now(),
    atualizado_em       timestamp without time zone DEFAULT now(),
    CONSTRAINT uq_fp_orcamentos_mensais UNIQUE (id_usuario, id_classificacao, competencia),
    CONSTRAINT ck_fp_orcamentos_mensais_dia1 CHECK (EXTRACT(DAY FROM competencia) = 1)
);

ALTER TABLE public.fp_orcamentos_mensais ENABLE ROW LEVEL SECURITY;

-- Carga: o valor atual de cada classificação em cada mês de 07/2026 a 11/2026,
-- respeitando:
--   * classificação criada depois do mês não entra nele (LIFE e SUPABASE nasceram em 11/2026);
--   * classificação inativa só entra até o último mês em que teve lançamento
--     (PARCELA CASA: última parcela em 10/2026, sai de 11/2026 em diante).
INSERT INTO public.fp_orcamentos_mensais (id_usuario, id_classificacao, competencia, valor_orcado)
SELECT c.id_usuario, c.id, m.competencia::date, c.valor_orcado
FROM public.fp_classificacoes c
CROSS JOIN generate_series(DATE '2026-07-01', DATE '2026-11-01', INTERVAL '1 month') AS m(competencia)
WHERE COALESCE(c.valor_orcado, 0) <> 0
  AND m.competencia >= date_trunc('month', c.criado_em)
  AND (c.ativo
       OR m.competencia <= (SELECT max(l.competencia) FROM public.fp_lancamentos l
                            WHERE l.id_classificacao = c.id))
ON CONFLICT (id_usuario, id_classificacao, competencia) DO NOTHING;
