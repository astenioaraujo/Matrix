-- Migração dos 16 contratos / 1.004 parcelas reais (EMP011 e EMP012).
INSERT INTO public.financeiro_emprestimos (
    id_emprestimo, cod_empresa, descricao, valor_contratado,
    quantidade_parcelas, data_primeiro_vencimento, ativo, criado_em, atualizado_em
)
OVERRIDING SYSTEM VALUE
SELECT
    e.id_emprestimo,
    e.cod_empresa,
    e.descricao || CASE WHEN NULLIF(TRIM(e.instituicao), '') IS NOT NULL
                        THEN ' — ' || TRIM(e.instituicao) ELSE '' END,
    e.valor_contratado,
    COALESCE(qp.qtd, 0),
    e.data_primeiro_vencimento,
    e.ativo,
    e.criado_em,
    e.atualizado_em
FROM public.financeiro_emprestimos_legado e
LEFT JOIN (
    SELECT id_emprestimo, COUNT(*) AS qtd
    FROM public.financeiro_emprestimos_parcelas_legado
    GROUP BY id_emprestimo
) qp ON qp.id_emprestimo = e.id_emprestimo;

SELECT setval(
    pg_get_serial_sequence('public.financeiro_emprestimos', 'id_emprestimo'),
    COALESCE((SELECT MAX(id_emprestimo) FROM public.financeiro_emprestimos), 1)
);

INSERT INTO public.financeiro_emprestimos_parcelas (
    id_emprestimo, cod_empresa, numero_parcela, data_vencimento,
    valor_principal, valor_juros, pago, data_pagamento, criado_em, atualizado_em
)
SELECT
    id_emprestimo, cod_empresa, numero_parcela, data_vencimento,
    valor_principal, valor_juros, (situacao = 'PAGO'), data_pagamento, criado_em, atualizado_em
FROM public.financeiro_emprestimos_parcelas_legado
ORDER BY id_emprestimo, numero_parcela;
