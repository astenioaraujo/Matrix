-- Parâmetros do ciclo de aferições, uma linha por empresa (Operações → Aferições).
--
-- dia_semana: 0 = segunda ... 4 = sexta (mesma numeração do date.weekday() do Python).
-- frequencia: SEMANAL, DUAS_SEMANAS, TRES_SEMANAS ou MENSAL.
-- data_referencia: uma data em que um ciclo começa; só é exigida em DUAS_SEMANAS e
-- TRES_SEMANAS, em que o dia da semana sozinho não diz qual é a semana do ciclo.
--
-- Empresa sem linha = sem aviso de aferição faltante.

CREATE TABLE IF NOT EXISTS public.afericoes_parametros (
    id_parametro     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa      character varying NOT NULL UNIQUE,
    dia_semana       integer NOT NULL,
    frequencia       character varying NOT NULL DEFAULT 'SEMANAL',
    data_referencia  date,
    criado_em        timestamp without time zone DEFAULT now(),
    atualizado_em    timestamp without time zone DEFAULT now()
);

ALTER TABLE public.afericoes_parametros ENABLE ROW LEVEL SECURITY;

