-- Canivete Suíço → Gerenciador de Problemas (11/11/2026).
--
-- Problemas por EMPRESA (não por usuário, ao contrário de Finanças Pessoais):
-- todo usuário da empresa com a permissão vê as mesmas pastas e problemas.
-- O processo começa pela pasta; dentro dela, os problemas.
--
-- Nada derivado vira coluna: contagem de abertos/resolvidos e dias em aberto
-- são calculados na consulta.

CREATE TABLE IF NOT EXISTS public.problemas_pastas (
    id_pasta            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa         character varying NOT NULL,
    nome                character varying NOT NULL,
    descricao           text,
    ordem               integer DEFAULT 10,
    id_usuario_criacao  integer,
    criado_em           timestamp without time zone DEFAULT now(),
    atualizado_em       timestamp without time zone DEFAULT now()
);

-- Nome de pasta não se repete na empresa (sem diferenciar maiúsculas).
CREATE UNIQUE INDEX IF NOT EXISTS uq_problemas_pastas_nome
    ON public.problemas_pastas (cod_empresa, upper(btrim(nome)));

ALTER TABLE public.problemas_pastas ENABLE ROW LEVEL SECURITY;


CREATE TABLE IF NOT EXISTS public.problemas (
    id_problema         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa         character varying NOT NULL,
    -- Pasta com problema não se exclui (a tela recusa); sem CASCADE de propósito.
    id_pasta            integer NOT NULL REFERENCES public.problemas_pastas(id_pasta),
    titulo              character varying NOT NULL,
    descricao           text,
    status              character varying NOT NULL DEFAULT 'ABERTO',   -- ABERTO / EM_ANDAMENTO / RESOLVIDO
    prioridade          character varying NOT NULL DEFAULT 'MEDIA',    -- ALTA / MEDIA / BAIXA
    responsavel         character varying,
    solucao             text,
    resolvido_em        timestamp without time zone,
    ordem               integer DEFAULT 10,
    id_usuario_criacao  integer,
    criado_em           timestamp without time zone DEFAULT now(),
    atualizado_em       timestamp without time zone DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_problemas_pasta ON public.problemas (cod_empresa, id_pasta);

ALTER TABLE public.problemas ENABLE ROW LEVEL SECURITY;


-- Permissão. Não é concedida a ninguém: só o superusuário passa por bypass.
INSERT INTO permissoes_catalogo (sistema, opcao, descricao, ordem, ativo)
SELECT v.sistema, v.opcao, v.descricao, v.ordem, TRUE
FROM (VALUES
    ('CANIVETE', 'PROBLEMAS', 'Gerenciador de Problemas', 1320)
) AS v(sistema, opcao, descricao, ordem)
WHERE NOT EXISTS (
    SELECT 1 FROM permissoes_catalogo p
    WHERE p.sistema = v.sistema AND p.opcao = v.opcao
);
