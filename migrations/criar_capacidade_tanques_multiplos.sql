-- Tanques múltiplos (Operações → Configurações → Capacidade de Tanques), 25/11/2026.
--
-- A capacidade de `capacidade_tanques` é por filial × produto. Em alguns postos
-- ela é a soma de mais de um tanque físico do mesmo produto (Ipaumirim:
-- gasolina = 2 × 7.500). Esta tabela guarda a composição, uma linha por tanque.
--
-- Não há flag "tem vários tanques": ter linhas aqui É ter vários tanques (o
-- checkbox da tela só reflete isso). Um flag à parte seria a mesma verdade em
-- dois lugares.
--
-- Ainda não é lida por nada além da própria tela: vai ser usada numa
-- implementação futura. A capacidade total continua sendo a de
-- `capacidade_tanques`; a tela só grava a composição quando a soma fecha.

BEGIN;

CREATE TABLE IF NOT EXISTS public.capacidade_tanques_multiplos (
    id_tanque_multiplo  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa         character varying NOT NULL,
    cod_filial          integer NOT NULL,
    cod_produto         character varying NOT NULL,
    identificacao       character varying,
    capacidade          numeric NOT NULL CHECK (capacidade > 0),
    ordem               integer DEFAULT 10,
    criado_em           timestamp without time zone DEFAULT now(),
    atualizado_em       timestamp without time zone DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_capacidade_tanques_multiplos
    ON public.capacidade_tanques_multiplos (cod_empresa, cod_filial, cod_produto);

ALTER TABLE public.capacidade_tanques_multiplos ENABLE ROW LEVEL SECURITY;

-- Carga EMP010: Afogados I (14) e Ipaumirim (22). Etanol não mexe.
INSERT INTO public.capacidade_tanques_multiplos
       (cod_empresa, cod_filial, cod_produto, identificacao, capacidade, ordem)
SELECT v.*
  FROM (VALUES
      ('EMP010', 14, 'C1', 'TQ 1', 15000::numeric, 10),
      ('EMP010', 14, 'C1', 'TQ 2', 10000::numeric, 20),
      ('EMP010', 14, 'C5', 'TQ 1', 15000::numeric, 10),
      ('EMP010', 14, 'C5', 'TQ 2', 10000::numeric, 20),
      ('EMP010', 22, 'C1', 'TQ 1',  7500::numeric, 10),
      ('EMP010', 22, 'C1', 'TQ 2',  7500::numeric, 20),
      ('EMP010', 22, 'C5', 'TQ 3', 15000::numeric, 10),
      ('EMP010', 22, 'C5', 'TQ 4', 15000::numeric, 20)
  ) AS v(cod_empresa, cod_filial, cod_produto, identificacao, capacidade, ordem)
 WHERE NOT EXISTS (
     SELECT 1 FROM public.capacidade_tanques_multiplos m
      WHERE m.cod_empresa = v.cod_empresa
        AND m.cod_filial = v.cod_filial
        AND m.cod_produto = v.cod_produto
 );

COMMIT;
