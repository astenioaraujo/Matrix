FROM (VALUES
    ('MENU',                'Menu do PDV Matrix',            1600),
    ('VENDER',              'Realizar Vendas (PDV)',         1610),
    ('CONSULTAR_VENDAS',    'Consultar Vendas',              1620),
    ('CADASTROS',           'Cadastros do PDV',              1630),
    ('CLIENTES',            'Cadastro de Clientes',          1640),
    ('PRODUTOS',            'Cadastro de Produtos',          1650),
    ('VENDEDORES',          'Cadastro de Vendedores',        1660),
    ('CONTAS_FINANCEIRAS',  'Cadastro de Contas Financeiras', 1670),
    ('OPERADORAS_CARTAO',   'Cadastro de Operadoras de Cartão', 1680),
    ('LANCAMENTOS',         'Lançamentos do Fluxo de Caixa', 1690),
    ('NOTAS_PRAZO',         'Recebimento de Notas a Prazo',  1700),
    ('CAIXA_CENTRAL',       'Caixa Central de Vendas',       1710)
) AS v(opcao, descricao, ordem)
WHERE NOT EXISTS (
    SELECT 1 FROM permissoes_catalogo p
    WHERE p.sistema = 'PDV' AND p.opcao = v.opcao
);
