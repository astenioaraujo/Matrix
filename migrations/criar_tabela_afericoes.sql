-- Aferições de bicos (Operações → Aferições)
--
-- Vídeo de poucos minutos em que o posto escoa 20 litros num balde e compara
-- com o que o indicador do bico mostrou. diferenca_ml é a leitura informada
-- pelo posto (bico − 20.000 ml), positiva ou negativa; "normal" (dentro de
-- ±100 ml) é calculado na consulta, nunca persistido (convenção do projeto).
--
-- Cada linha é um evento (uma aferição), não um estado por dia — por isso
-- não há upsert por (filial, produto, bico, data) como em medições: o mesmo
-- bico pode ser aferido mais de uma vez no mesmo dia.
--
-- Retenção: a aplicação mantém só as duas aferições mais recentes de cada
-- (empresa, filial, produto, bico), apagando a mais antiga — e o vídeo dela
-- no Storage — a cada novo envio.

CREATE TABLE IF NOT EXISTS public.afericoes (
    id_afericao     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_empresa     character varying NOT NULL,
    cod_filial      integer NOT NULL,
    cod_produto     character varying NOT NULL,
    numero_bico     character varying NOT NULL,
    data_afericao   date NOT NULL,
    hora_afericao   time without time zone NOT NULL,
    id_usuario      integer NOT NULL,
    diferenca_ml    numeric NOT NULL DEFAULT 0,
    arquivo_video   character varying NOT NULL,
    observacao      character varying,
    criado_em       timestamp without time zone DEFAULT now(),
    atualizado_em   timestamp without time zone
);

CREATE INDEX IF NOT EXISTS ix_afericoes_bico
    ON public.afericoes (cod_empresa, cod_filial, cod_produto, numero_bico);

CREATE INDEX IF NOT EXISTS ix_afericoes_filial_data
    ON public.afericoes (cod_empresa, cod_filial, data_afericao);

ALTER TABLE public.afericoes ENABLE ROW LEVEL SECURITY;

